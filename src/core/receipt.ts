import type { LaunchConfig } from './model';

function canonicalize(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([key, item]) => [key, canonicalize(item)])
    );
  }
  return value;
}

export function canonicalConfig(config: LaunchConfig): string {
  return JSON.stringify(canonicalize(config));
}

export function configReceipt(config: LaunchConfig): string {
  const input = canonicalConfig(config);
  let hash = 0x811c9dc5;
  for (let index = 0; index < input.length; index += 1) {
    hash ^= input.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return `cp-${hash.toString(16).padStart(8, '0')}`;
}
